// Generates icons.css: only the Font Awesome Free icons that the site's pages
// actually use, drawn as CSS masks so existing <i class="fas fa-..."> markup keeps working.
// Re-run after adding a new icon:  cd tools && npm i && node build-icons.mjs
// Icons: Font Awesome Free (https://fontawesome.com/license/free) - CC BY 4.0.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const fa = path.dirname(require.resolve("@fortawesome/fontawesome-free/package.json"));
const root = path.resolve(import.meta.dirname, "..");
const meta = JSON.parse(fs.readFileSync(path.join(fa, "metadata/icon-families.json"), "utf8"));

// alias/class name -> canonical icon name
const canon = new Map();
for (const [name, info] of Object.entries(meta)) {
  canon.set(name, name);
  for (const a of info.aliases?.names ?? []) canon.set(a, name);
}

const famDir = { solid: "solid", regular: "regular", brands: "brands" };
const famOf = (cls) =>
  /\b(fa-brands|fab)\b/.test(cls) ? "brands" : /\b(fa-regular|far)\b/.test(cls) ? "regular" : "solid";

// collect (family, class-name) pairs from every page, including inline JS strings
const used = new Map(); // key "family:class" -> {family, cls}
for (const f of fs.readdirSync(root).filter((f) => f.endsWith(".html"))) {
  const text = fs.readFileSync(path.join(root, f), "utf8");
  for (const m of text.matchAll(/class=\\?["']([^"']*\bfa-[^"']*)["']/g)) {
    const fam = famOf(m[1]);
    for (const c of m[1].split(/\s+/)) {
      if (!/^fa-/.test(c) || ["fa-solid", "fa-regular", "fa-brands", "fa-2xl"].includes(c)) continue;
      used.set(`${fam}:${c}`, { fam, cls: c });
    }
  }
}

const famClass = { solid: [".fa-solid", ".fas"], regular: [".fa-regular", ".far"], brands: [".fa-brands", ".fab"] };
let css = `/* Font Awesome Free icons (CC BY 4.0, https://fontawesome.com/license/free) used by this site, as CSS masks.
   Generated by tools/build-icons.mjs - do not edit by hand. */
.fa-solid,.fas,.fa-regular,.far,.fa-brands,.fab{display:inline-block;font-style:normal;line-height:1;vertical-align:-.125em;text-rendering:auto}
.fa-solid::before,.fas::before,.fa-regular::before,.far::before,.fa-brands::before,.fab::before{content:"";display:block;height:1em;width:var(--fa-w,1em);background:currentColor;-webkit-mask:var(--fa-m) center/contain no-repeat;mask:var(--fa-m) center/contain no-repeat}
.fa-2xl{font-size:2em;line-height:.03125em;vertical-align:-.1875em}
.fa-2xl::before{margin:calc((.03125em - 1em) / 2) 0}
`;
const missing = [];
// group alias classes (fa-phone / fa-phone-alt) that resolve to the same glyph so each path is emitted once
const groups = new Map(); // "family:canonical" -> Set(class names)
for (const { fam, cls } of used.values()) {
  const name = canon.get(cls.slice(3));
  const file = name && path.join(fa, "svgs", famDir[fam], `${name}.svg`);
  if (!file || !fs.existsSync(file)) { missing.push(`${fam}:${cls}`); continue; }
  const key = `${fam}:${name}`;
  if (!groups.has(key)) groups.set(key, new Set());
  groups.get(key).add(cls);
}
for (const [key, classes] of [...groups].sort((a, b) => a[0].localeCompare(b[0]))) {
  const [fam, name] = key.split(":");
  const svg = fs.readFileSync(path.join(fa, "svgs", famDir[fam], `${name}.svg`), "utf8");
  const vb = svg.match(/viewBox="0 0 (\d+) (\d+)"/);
  const d = svg.match(/<path d="([^"]+)"/)[1];
  const w = (+vb[1] / +vb[2]).toFixed(3).replace(/0+$/, "").replace(/\.$/, "");
  const uri = `data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${vb[1]} ${vb[2]}'%3E%3Cpath d='${d}'/%3E%3C/svg%3E`;
  const sel = [...classes].flatMap((cls) => famClass[fam].map((c) => `${c}.${cls}`)).join(",");
  css += `${sel}{--fa-w:${w}em;--fa-m:url("${uri}")}\n`;
}
fs.writeFileSync(path.join(root, "icons.css"), css);
console.log(`icons.css: ${used.size} icon classes, ${(css.length / 1024).toFixed(1)} KB`, missing.length ? `MISSING: ${missing}` : "");
